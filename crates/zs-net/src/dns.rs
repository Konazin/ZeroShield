//! DNS sinkhole fragments for dnsmasq and Unbound.
//!
//! ZeroShield never edits the resolver configuration in place: it writes a
//! fragment that the user (or the installer) includes from the resolver
//! config, e.g. `conf-file=/etc/zeroshield/dns.conf` for dnsmasq.

use std::path::{Path, PathBuf};

use zs_core::error::{ZsError, ZsResult};

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DnsBackend {
    Dnsmasq,
    Unbound,
}

impl DnsBackend {
    pub fn as_str(self) -> &'static str {
        match self {
            DnsBackend::Dnsmasq => "dnsmasq",
            DnsBackend::Unbound => "unbound",
        }
    }
}

/// Generate the sinkhole fragment for the given domains.
pub fn generate(backend: DnsBackend, domains: &[String]) -> String {
    let mut s = String::new();
    s.push_str("# Generated by ZeroShield - do not edit by hand.\n");
    s.push_str("# Blocked domains resolve to 0.0.0.0 (sinkhole).\n");
    match backend {
        DnsBackend::Dnsmasq => {
            for d in domains {
                s.push_str(&format!("address=/{d}/0.0.0.0\n"));
            }
        }
        DnsBackend::Unbound => {
            for d in domains {
                s.push_str(&format!("local-zone: \"{d}\" static\n"));
                s.push_str(&format!("local-data: \"{d} A 0.0.0.0\"\n"));
            }
        }
    }
    s
}

/// Write the fragment into the ZeroShield data dir.
pub fn write_fragment(
    data_dir: &Path,
    backend: DnsBackend,
    domains: &[String],
) -> ZsResult<PathBuf> {
    let path = data_dir.join(format!("dns-{}.conf", backend.as_str()));
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| ZsError::io(parent, e))?;
    }
    std::fs::write(&path, generate(backend, domains)).map_err(|e| ZsError::io(&path, e))?;
    Ok(path)
}

/// Install the fragment into the resolver's include directory (requires root).
pub fn install(fragment: &Path, target_dir: &Path, backend: DnsBackend) -> ZsResult<PathBuf> {
    use zs_core::util::is_root;
    if !is_root() {
        return Err(ZsError::Permission(
            "installing DNS fragments requires root".into(),
        ));
    }
    if !target_dir.exists() {
        return Err(ZsError::NotFound(format!(
            "{} does not exist (is {} installed?)",
            target_dir.display(),
            backend.as_str()
        )));
    }
    let target = target_dir.join("zeroshield.conf");
    std::fs::copy(fragment, &target).map_err(|e| ZsError::io(&target, e))?;
    Ok(target)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dnsmasq_fragment() {
        let text = generate(DnsBackend::Dnsmasq, &["evil.example".into()]);
        assert!(text.contains("address=/evil.example/0.0.0.0"));
    }

    #[test]
    fn unbound_fragment() {
        let text = generate(DnsBackend::Unbound, &["evil.example".into()]);
        assert!(text.contains("local-zone: \"evil.example\" static"));
        assert!(text.contains("local-data: \"evil.example A 0.0.0.0\""));
    }

    #[test]
    fn writes_fragment() {
        let dir = tempfile::tempdir().unwrap();
        let path = write_fragment(dir.path(), DnsBackend::Dnsmasq, &["a.example".into()]).unwrap();
        assert!(path.exists());
        assert!(std::fs::read_to_string(path).unwrap().contains("a.example"));
    }
}
